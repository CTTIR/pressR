test_that("bundles preserve layout, metadata and measurements and detect tampering", {
  tr <- pr_example_trial("custom")
  tr$metadata$condition <- factor("b", levels = c("a", "b"))
  path <- tempfile()
  on.exit(unlink(path, recursive = TRUE))
  pr_write_bundle(tr, path)
  out <- pr_read_auto(path)
  expect_equal(out$pressure, tr$pressure, tolerance = 1e-12)
  expect_equal(out$time, tr$time, tolerance = 1e-12)
  expect_identical(out$layout, tr$layout)
  expect_identical(out$metadata$condition, tr$metadata$condition)
  expect_error(pr_write_bundle(tr, path), "already exists")
  cat("changed", file = file.path(path, "pressure.csv"), append = TRUE)
  expect_error(pr_read_bundle(path), "checksum")
})

test_that("long CSV rejects duplicate and missing observations", {
  path <- tempfile(fileext = ".csv")
  on.exit(unlink(path))
  lay <- pr_layout_from_index_map(matrix(1:4, 2, 2))
  d <- expand.grid(sensor_id = 1:4, frame = 1:3)
  d$pressure <- seq_len(nrow(d))
  d$time <- (d$frame - 1) / 10
  write.csv(d, path, row.names = FALSE)
  tr <- pr_read_csv(path, layout = lay, verbose = FALSE)
  expect_equal(tr$sampling_hz, 10)
  expect_equal(tr$pressure[1, ], 1:4)
  write.csv(rbind(d, d[1, ]), path, row.names = FALSE)
  expect_error(pr_read_csv(path, layout = lay, verbose = FALSE), "Duplicate")
  write.csv(d[-1, ], path, row.names = FALSE)
  expect_error(pr_read_csv(path, layout = lay, verbose = FALSE), "Incomplete")
})

