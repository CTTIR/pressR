test_that("inventory and archive extraction preserve aliases and bytes", {
  skip_if_not_installed("archive")
  root <- tempfile()
  dir.create(root)
  on.exit(unlink(root, recursive = TRUE))
  writeLines("pressure", file.path(root, "one.asc"))
  file.copy(file.path(root, "one.asc"), file.path(root, "two.asc"))
  inv <- pr_inventory(root)
  expect_true(all(inv$duplicate_content))
  expect_equal(nrow(inv), 2)
  expect_identical(inv$relative_path, c("one.asc", "two.asc"))
  path <- file.path(root, "data.tar")
  old <- setwd(root)
  on.exit(setwd(old), add = TRUE)
  utils::tar(path, files = c("one.asc", "two.asc"), compression = "none", tar = "internal")
  setwd(old)
  out <- pr_extract_archive(path, "one.asc", file.path(root, "extracted"))
  expect_identical(out$sha256, inv$sha256[1])
  expect_error(pr_extract_archive(path, "../one.asc", file.path(root, "bad")), "Unsafe")
  expect_error(pr_extract_archive(path, "one.asc", file.path(root, "small"), max_bytes = 1), "budget")
})

