test_that("reference replay is bound to the exact recording", {
  tr <- pr_example_trial("saddle_horse")
  cycles <- pr_calc_stride_cycles(tr)
  locked <- pr_lock_cycles(tr, cycles)
  replay <- pr_temporal_profile(tr, "reference", locked)
  expect_identical(replay$cycles, cycles)
  expect_true(replay$settings$exact_reference_replay)
  tr$pressure[1, 1] <- tr$pressure[1, 1] + 1
  expect_error(pr_temporal_profile(tr, "reference", locked), "exact trial")
  expect_error(pr_lock_cycles(tr, transform(cycles, duration_s = duration_s + 1)), "timing")
})

