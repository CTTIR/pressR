test_that("explicit acquisition linking rejects ambiguous identities", {
  rec <- data.frame(recording_id = c("r1", "r2"), subject = c("A", "B"), condition = "walk")
  assets <- data.frame(asset_id = c("hr1", "hr2"), subject = c("A", "B"), condition = "walk", sha256 = "same")
  linked <- pr_link_assets(rec, assets, c("subject", "condition"))
  expect_identical(linked$recording_id, c("r1", "r2"))
  expect_true(all(linked$duplicate_content))
  more <- rbind(assets, transform(assets[1, ], asset_id = "hr3"))
  expect_error(pr_link_assets(rec, more, c("subject", "condition")), "Ambiguous")
  expect_equal(nrow(pr_link_assets(rec, more, c("subject", "condition"), "one-to-many")), 3)
  expect_error(pr_link_assets(transform(rec, subject = "A"), assets, c("subject", "condition")), "Ambiguous")
  assets$subject[2] <- "C"
  expect_error(pr_link_assets(rec, assets, c("subject", "condition")), "no matching")
  linked <- pr_link_assets(rec, assets, c("subject", "condition"), allow_unmatched = TRUE)
  expect_identical(linked$link_status[2], "unmatched")
  expect_identical(attr(linked, "unused_recording_ids"), "r2")
  expect_error(pr_link_assets(rec, transform(assets, subject = NA), c("subject", "condition")), "complete")
})

